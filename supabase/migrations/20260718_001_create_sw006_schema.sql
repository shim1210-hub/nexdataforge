begin;

create extension if not exists pgcrypto;

create sequence profile_id_sequence start with 1 minvalue 1;
create sequence generation_job_id_sequence start with 1 minvalue 1;
create sequence board_id_sequence start with 1 minvalue 1 maxvalue 9999999;
create sequence page_id_sequence start with 1 minvalue 1;
create sequence main_section_id_sequence start with 1 minvalue 1;
create sequence generated_file_id_sequence start with 1 minvalue 1;

create or replace function next_profile_id()
returns varchar(22)
language sql
as $$
  select ('USR-' || nextval('profile_id_sequence')::text)::varchar(22);
$$;

create or replace function next_generation_job_id()
returns varchar(22)
language sql
as $$
  select ('GE-' || nextval('generation_job_id_sequence')::text)::varchar(22);
$$;

create or replace function next_board_id()
returns varchar(11)
language plpgsql
as $$
declare
  next_number bigint := nextval('board_id_sequence');
begin
  if next_number > 9999999 then raise exception '게시판 ID를 9999999개보다 많이 생성할 수 없습니다.'; end if;
  return 'BBS-' || next_number::text;
end;
$$;

create or replace function next_page_id()
returns varchar(22)
language sql
as $$
  select ('PG-' || nextval('page_id_sequence')::text)::varchar(22);
$$;

create or replace function next_main_section_id()
returns varchar(22)
language sql
as $$
  select ('MS-' || nextval('main_section_id_sequence')::text)::varchar(22);
$$;

create or replace function next_generated_file_id()
returns varchar(22)
language sql
as $$
  select ('GEF-' || nextval('generated_file_id_sequence')::text)::varchar(22);
$$;

create or replace function next_site_id()
returns bigint
language plpgsql
as $$
declare
  day_prefix bigint := to_char(current_date, 'YYYYMMDD')::bigint * 10000;
  next_number integer;
begin
  perform pg_advisory_xact_lock(hashtext('sites_daily_id_' || current_date::text));
  select coalesce(max((id - day_prefix)::integer), 0) + 1
    into next_number
    from sites
   where id between day_prefix and day_prefix + 9999;
  if next_number > 9999 then raise exception '하루에 사이트 ID를 9999개보다 많이 생성할 수 없습니다.'; end if;
  return day_prefix + next_number;
end;
$$;

create table profiles (
  id varchar(22) default next_profile_id(),
  auth_user_id uuid,
  login_id varchar(100),
  display_name varchar(100),
  email varchar(200),
  company_slug varchar(100),
  access_level varchar(30) default 'SITE_USER',
  password_hash text,
  phone varchar(50),
  avatar_url text,
  is_platform_admin boolean default false,
  is_active boolean default true,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  primary key (id)
);

create table sites (
  id bigint default next_site_id(),
  company_slug varchar(100),
  name varchar(200),
  industry varchar(100),
  manager_name varchar(100),
