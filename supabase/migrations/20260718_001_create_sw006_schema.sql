create table pages (
  id varchar(22) default next_page_id(),
  site_id bigint,
  menu_id bigint,
  slug varchar(200),
  title varchar(300),
  content jsonb default '{}'::jsonb,
  seo_title varchar(300),
  seo_description text,
  status varchar(30) default 'DRAFT',
  published_at timestamptz,
  created_by varchar(22),
  updated_by varchar(22),
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  primary key (id)
);

create table boards (
  id varchar(11) default next_board_id(),
  site_id bigint,
  code varchar(100),
  name varchar(200),
  description text,
  allow_files boolean default true,
  is_enabled boolean default true,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  primary key (id)
);

create table board_posts (
  id bigint generated always as identity,
  site_id bigint,
  board_id varchar(11),
  title varchar(500),
  content text,
  status varchar(30) default 'DRAFT',
  is_notice boolean default false,
  view_count bigint default 0,
  author_id varchar(22),
  published_at timestamptz,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  primary key (id)
);

create table board_files (
  id uuid default gen_random_uuid(),
  post_id bigint,
  asset_id uuid,
  sort_order integer default 0,
  created_at timestamptz default now(),
  primary key (id)
);

create table generation_jobs (
  id varchar(22) default next_generation_job_id(),
  site_id bigint,
  status varchar(30) default 'QUEUED',
  progress smallint default 0,
  current_step varchar(200),
  log jsonb default '[]'::jsonb,
  error_message text,
  requested_by varchar(22),
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  primary key (id)
);

create table generated_files (
  id varchar(22) default next_generated_file_id(),
  site_id bigint,
  generation_job_id varchar(22),
  relative_path text,
  content_hash varchar(200),
  size_bytes bigint default 0,
  created_at timestamptz default now(),
  primary key (id)
);

